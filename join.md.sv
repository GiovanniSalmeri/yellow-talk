## Hur man använder forumet

+ Skriv en kort och konkret ämnesrad till varje fråga som tydligt visar vad du menar.
+ Innan du ställer enkla frågor bör du först läsa manualer, besöka webbplatser och liknande. Frågor som ger upphov till en diskussion är däremot alltid välkomna.
+ Även om det inlägg med vilket du inleder en diskussion kallas en ”fråga”, kan du lägga upp en kommentar om ett relevant ämne. I det fallet är det underförstått: ”Vad tycker du?”.
+ Innan du svarar, läs igenom hela tråden och undvik svar på bara en rad.
+ Om du vill ta upp ett annat ämne, börja med en ny fråga.
+ Andra deltagare vill diskutera saker med dig: använd därför inte verktyg för artificiell intelligens när du skriver dina inlägg.
+ Undvik att lägga upp privat information om dig själv eller andra personer.
+ Skriv på ett sätt som visar respekt för alla och ignorera inlägg som inte gör det.
+ Kontrollera innan du publicerar att ditt meddelande är tydligt och felfritt. När du väl har tryckt på knappen ”Publicera” kan du inte redigera det längre.
+ Förvänta dig inte att deltagarna ska läsa och svara omedelbart: skriftliga diskussioner uppmuntrar till mer eftertanke.

## Hur man använder RSS-flöden

För att hålla dig uppdaterad om nya inlägg kan du använda en RSS-läsare. Här är några att välja mellan:

+ Android: [FeedFlow](https://play.google.com/store/search?q=FeedFlow&c=apps) ([F-Droid](https://f-droid.org/packages/com.prof18.feedflow/)), [Feeder](https://play.google.com/store/search?q=Feeder&c=apps) ([F-Droid](https://f-droid.org/en/packages/com.nononsenseapps.feeder/)), [RSS Reader](https://f-droid.org/en/packages/de.lolo.rssreader/), [Aggregator News](https://play.google.com/store/search?q=Aggregator%20News&c=apps)
+ Linux: [Liferea](https://github.com/lwindolf/liferea), [GFeeds](https://gfeeds.gabmus.org/), [Akregator](https://apps.kde.org/akregator/)
+ iOS: [NetNewsWire](https://apps.apple.com/it/app/netnewswire-rss-reader/id1480640210)
+ MacOS: [NetNewsWire](https://netnewswire.com/)
+ Windows: [FeedFlow](https://apps.microsoft.com/detail/9n5t1rfbb6v5), [Fluent Reader](https://apps.microsoft.com/detail/9p71fc94lrh8)

Installera ett av programmen och lägg till det flöde du vill ha. Yellow Talk erbjuder ett generellt flöde, som innehåller uppdateringar från alla grupper, samt ett specifikt flöde för varje grupp. Du kan använda aggregatorernas funktion för automatisk upptäckt.

## Hur man använder Markdown

Du kan använda vissa Markdown-taggar i dina meddelanden.

För att formatera text:

```
Normal *kursiv* **fet**
```

Så här skapar du stycken:

```
Detta är det första stycket. Nästa stycke måste separeras med en tom rad.

Detta är det andra stycket.
```

Så här skapar du blockcitat:

```
> Detta är ett citat.
```

Så här skapar du listor:

```
+ Första punkten
+ Andra punkten
+ Tredje punkten
```

Så här skapar du länkar:

```
Länk till en [webbplats](https://example.org)
Länk till en [bild](https://example.org/bild.jpg)
```

Om en bild inte finns tillgänglig online kan du först ladda upp den till en fildelningstjänst, till exempel [ImgBB](https://imgbb.com/).
